#!/usr/bin/env bash
# Regenerate docs/CLAIMS.md: the exact statement and axioms of every headline Lean theorem,
# printed by Lean itself. With --check, fail if docs/CLAIMS.md is out of date.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
thms=(
  "Adequacy:eval_iff:the reference interpreter computes exactly the big-step semantics"
  "Adequacy:eval_fuel_irrelevant:fuel never changes a finished answer"
  "Adequacy:Eval.det:Verse Core is deterministic"
  "Adequacy:Runs.det:a program run has one outcome and one output"
  "Adequacy:Prog.run_sound:Prog.run is sound"
  "Adequacy:Prog.run_complete:Prog.run is complete"
  "Bounded:evalB_sound:the depth-bounded interpreter of openverse run is eval whenever it does not stop for depth"
  "Bounded:evalB_complete:with a depth budget at least the fuel, the bounded interpreter is eval"
  "Bounded:Prog.runB_sound:openverse run computes Prog.run whenever it does not hit its depth bound"
  "Derived:ite_rollback:a failed if condition is rolled back"
  "Derived:notE_ok:a successful not e discards the effects of e"
  "Derived:notE_notE_ok:not not e is a pure test"
  "Derived:optionE_none:option{} of a failure is empty and effect-free"
  "Derived:orE_right:a or b with a failing a is b from the original state"
  "Derived:altE_sel:a choice's index slot selects its alternative"
  "Derived:chooseFirst_brk:a choice breaks out at its first success, the alternatives before it rolled back"
  "Derived:chooseFirst_none:a choice with no success ends with no value"
  "Derived:firstE_of_brk:clauses that break make firstE succeed"
  "Derived:firstE_of_ok:clauses that end normally make firstE fail"
  "Effects:Eval.no_fail:<decides> soundness for expressions"
  "Effects:Runs.no_fail:a program whose Main is not <decides> never fails"
  "Scoping:Eval.scoped_ok:well-scoped programs raise no slot or call error and keep frame sizes"
  "TypeSafety:Eval.typed:preservation"
  "TypeSafety:Runs.typed:type safety of programs"
  "TypeSafety:Typed.subst:the substitution lemma: a typing with type variables holds at every instance"
  "TypeSafety:hasTy_sub:subtyping is sound: a value of a type is a value of every type above it"
  "TypeCheck:tc_sound:the type checker is sound"
  "TypeCheck:Prog.checkTypes_sound:checkTypes establishes ProgTyped"
  "Control:Runs.no_control:break never escapes its loop"
  "Writes:Eval.no_writes:an expression that does not write keeps every existing object"
  "Check:Prog.check_ok:Prog.check establishes the hypotheses of no_fail and scoped_ok"
  "Guarantees:Prog.accepted:everything a program accepted by the front end is guaranteed"
  "Guarantees:Prog.accepted_no_writes:a function without writes keeps every existing object"
  "Seams:apply_mul:int multiplication in the terms of the C law"
  "Seams:apply_floorDiv:Floor(a/b) in the terms of the C law"
  "Seams:apply_quotient:Quotient in the terms of the C law"
  "Seams:apply_modulo:Mod in the terms of the C law"
  "Seams:apply_min_neg_one:the (INT64_MIN, -1) cases"
)
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
{
  echo "import OpenVerse"
  echo "open OpenVerse"
  echo "set_option pp.proofs false"
  for t in "${thms[@]}"; do
    IFS=: read -r _ name _ <<<"$t"
    echo "#check @$name"
    echo "#print axioms $name"
  done
} > "$tmp/Claims.lean"
lake env lean "$tmp/Claims.lean" > "$tmp/out.txt" 2>&1
python3 -I - "$tmp/out.txt" "$tmp/CLAIMS.md" "${thms[@]}" <<'PY'
import sys, re
out, dst, thms = sys.argv[1], sys.argv[2], sys.argv[3:]
stmts, axs, cur = [], [], None
for line in open(out).read().split("\n"):
    if line and not line.startswith(" ") and not line.startswith("'"):
        cur = [line]
    elif line.startswith("'"):
        stmts.append("\n".join(cur)); axs.append(line); cur = None
    elif cur is not None:
        cur.append(line)
if len(stmts) != len(thms):
    sys.exit("gen-claims: expected %d theorems, Lean printed %d:\n%s" % (len(thms), len(stmts), open(out).read()))
lines = ["# Lean claims of openverse", "",
         "Generated by `scripts/gen-claims.sh` from the Lean sources: each statement and its axioms are",
         "printed by Lean itself (`#check`, `#print axioms`). `scripts/check.sh` fails when this file is",
         "out of date. The proofs are in `OpenVerse/Core/`.", ""]
for i, t in enumerate(thms):
    f, name, desc = t.split(":", 2)
    stmt = stmts[i].strip()
    ax = axs[i].strip()
    ax = re.sub(r"^'[^']*' depends on axioms: ", "", ax)
    lines += [f"## `{name}`: {desc}", "", f"`OpenVerse/Core/{f}.lean`; axioms: {ax}", "", "```lean", stmt, "```", ""]
open(dst, "w").write("\n".join(lines))
PY
if [[ "${1:-}" == "--check" ]]; then
  cmp -s "$tmp/CLAIMS.md" docs/CLAIMS.md || { echo "docs/CLAIMS.md is out of date: run scripts/gen-claims.sh" >&2; exit 1; }
  echo "claims: docs/CLAIMS.md is up to date"
else
  cp "$tmp/CLAIMS.md" docs/CLAIMS.md; echo "wrote docs/CLAIMS.md"
fi

#!/usr/bin/env bash
# Regenerate proofs/quickproof/loader/project/env/loader_wellscoped.c: the input distribution of
# the loader law's native and interpreter runs (not part of any theorem). Needs `lake build`.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ov="$root/.lake/build/bin/openverse"
s="$(mktemp -d)"; trap 'rm -rf "$s"' EXIT
for f in "$root"/tests/verse/*.verse; do "$ov" emit "$f" -o "$s/$(basename "$f" .verse).vbc"; done
cp "$root"/tests/core/*.vbc "$s/"
for i in $(seq 1 40); do "$ov" gen "$i" --emit "$s/gen$i.vbc"; done
python3 -I - "$s" "$root/proofs/quickproof/loader/project/env/loader_wellscoped.c" <<'PY'
import sys, os
d, dst = sys.argv[1], sys.argv[2]
samples = [(f, open(os.path.join(d, f), 'rb').read()) for f in sorted(os.listdir(d))]
samples = [(f, b) for f, b in samples if len(b) <= 4096]
out = ["""/* Value distributions for the native and interpreter runs of loader_wellscoped (not part of any
 * theorem). Uniform bytes almost never form an OVBC program, so nondet_size picks one of the
 * programs below (the compiled test suite and random programs of OpenVerse/Core/Gen.lean, written
 * by `openverse emit`), sometimes corrupts one byte or truncates it, and nondet_bytes then writes
 * it. Generated by scripts/gen-loader-env.sh. */
#include <stddef.h>
#include <stdint.h>
#include "quickproof.h"

extern uint64_t quickproof_rnd(void);
"""]
for i, (f, b) in enumerate(samples):
    out.append(f"/* {f} */\nstatic const uint8_t s{i}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};")
out.append("static const uint8_t *const samples[] = {" + ",".join(f"s{i}" for i in range(len(samples))) + "};")
out.append("static const size_t sizes[] = {" + ",".join(str(len(b)) for _, b in samples) + "};")
out.append(f"#define NSAMPLES {len(samples)}")
out.append(open(os.path.join(os.path.dirname(dst), "..", "..", "env-tail.c.in")).read())
open(dst, 'w').write("\n".join(out))
print(len(samples), "samples")
PY

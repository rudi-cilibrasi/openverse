(* pick(x) on an int64_t: the bytes of x are a tuchar array before the call *)
Lemma tlong_bytes: forall sh q, data_at_ sh tlong q |-- data_at_ sh (tarray tuchar 8) q.
Proof.
  intros. sep_apply (data_at__memory_block_cancel sh tlong q).
  apply memory_block_data_at__tarray_tuchar. rep_lia.
Qed.

(* The obligation of a qp_assert: its condition is not zero *)
Ltac assert_ok :=
  match goal with H: Int.repr (Z.b2z _) = Int.zero |- False =>
    revert H; simpl64; rewrite ?Int64.eq_true, ?Z.eqb_refl; intro H; exact (Int.one_not_zero H)
  end.

(* forward_if for an if (an && or ?:) that only sets the temporary id: the join gives it the value v *)
Ltac join_temp id v :=
  match goal with |- semax _ (PROPx ?P (LOCALx ?Q (SEPx ?R))) _ _ =>
    let Q' := remove_LOCAL2 constr:(cons (temp id v) nil) Q in
    forward_if (PROPx P (LOCALx (temp id v :: Q') (SEPx R)))
  end.

Ltac in64_hyp := match goal with E: in64 _ = _ |- _ => unfold st_of, out_of; rewrite E end.

(* The state between the nine blocks of main: a and b picked, r writable *)
Definition Inv (v_a v_b v_r: val) (gv: globals) (a b: Z) : environ -> mpred :=
  PROP ()
  LOCAL (lvar _r tlong v_r; lvar _b tlong v_b; lvar _a tlong v_a; gvars gv)
  SEP (data_at_ Tsh tlong v_r; data_at Tsh tlong (Vlong (Int64.repr b)) v_b;
       data_at Tsh tlong (Vlong (Int64.repr a)) v_a; has_ext tt).

Lemma body_main: semax_body (QPvarspecs p) Gmain f_main (_main, main_spec_std p).
Proof.
  start_function.
  assert_PROP (field_compatible tlong [] v_a) as FCa by entailer!.
  assert_PROP (field_compatible tlong [] v_b) as FCb by entailer!.
  assert (NNa: v_a <> nullval) by (intro E; rewrite E in FCa; destruct FCa as [X _]; exact X).
  assert (NNb: v_b <> nullval) by (intro E; rewrite E in FCb; destruct FCb as [X _]; exact X).
  sep_apply (tlong_bytes Tsh v_a).
  forward_call (v_a, 8, Tsh).
  { rewrite if_false by auto. cancel. }
  Intros bsa. rewrite if_false by auto.
  sep_apply (pick_tlong Tsh bsa v_a H H0 FCa). Intros ia.
  sep_apply (tlong_bytes Tsh v_b).
  forward_call (v_b, 8, Tsh).
  { rewrite if_false by auto. cancel. }
  Intros bsb. rewrite if_false by auto.
  sep_apply (pick_tlong Tsh bsb v_b H1 H2 FCb). Intros ib.
  rewrite <- (Int64.repr_signed ia), <- (Int64.repr_signed ib).
  pose proof (Int64.signed_range ia) as Ra. pose proof (Int64.signed_range ib) as Rb.
  forget (Int64.signed ia) as a. forget (Int64.signed ib) as b.
  clear H H0 H1 H2 bsa bsb.
  (* vx_add *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward. forward. forward_call (a, b).
  forward_if (Inv v_a v_b v_r gv a b).
  { in64_hyp. forward_call. forward. forward. forward. forward_call.
    { apply in64_spec; auto. }
    { assert_ok. }
    unfold Inv. entailer!. }
  { in64_hyp. forward_call. forward. forward_call. unfold Inv. entailer!. }
  unfold Inv. Intros.
  (* vx_sub *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward. forward. forward_call (a, b).
  forward_if (Inv v_a v_b v_r gv a b).
  { in64_hyp. forward_call. forward. forward. forward. forward_call.
    { apply in64_spec; auto. }
    { assert_ok. }
    unfold Inv. entailer!. }
  { in64_hyp. forward_call. forward. forward_call. unfold Inv. entailer!. }
  unfold Inv. Intros.
  (* vx_mul *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward. forward. forward_call (a, b).
  forward_if (Inv v_a v_b v_r gv a b).
  { in64_hyp. forward_call. forward. forward. forward. forward_call.
    { apply in64_spec; auto. }
    { assert_ok. }
    unfold Inv. entailer!. }
  { in64_hyp. forward_call. forward. forward_call. unfold Inv. entailer!. }
  unfold Inv. Intros.
  (* vx_neg *)
  forward. forward. forward_call (a, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward.
  forward_if (Inv v_a v_b v_r gv a b).
  { simpl64. rewrite st_of_ok, out_of_ok by rep_lia.
    forward_call. forward. forward. forward_call.
    { rewrite Int64.signed_zero. rep_lia. }
    { assert_ok. }
    unfold Inv. entailer!. }
  { simpl64. subst a. rewrite st_of_ovf, out_of_ovf by rep_lia.
    forward_call. forward. forward_call. unfold Inv. entailer!. }
  unfold Inv. Intros.
  (* vx_abs *)
  forward. forward. forward_call (a, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward.
  forward_if (Inv v_a v_b v_r gv a b).
  { simpl64. rewrite st_of_ok, out_of_ok by rep_lia.
    forward_call. forward.
    join_temp _t'9 (Vlong (Int64.repr (Z.abs a))).
    { simpl64. forward. forward.
      { entailer!. rewrite Int64.signed_zero. rep_lia. }
      entailer!. rewrite Z.abs_neq by lia. reflexivity. }
    { simpl64. forward. forward. entailer!. rewrite Z.abs_eq by lia. reflexivity. }
    forward. forward_call.
    { assert_ok. }
    unfold Inv. entailer!. }
  { simpl64. subst a. rewrite st_of_ovf, out_of_ovf by (rewrite Z.abs_neq by rep_lia; rep_lia).
    forward_call. forward. forward_call. unfold Inv. entailer!. }
  unfold Inv. Intros.
  (* vx_floordiv *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward.
  forward_if (Inv v_a v_b v_r gv a b).
  { simpl64. subst b. rewrite div_st_zero, div_out_zero.
    forward_call. forward. forward_call. unfold Inv. entailer!. }
  { simpl64. rewrite div_st_nz, div_out_nz by auto.
    forward.
    join_temp _t'12 (Vint (Int.repr (Z.b2z ((a =? MIN) && (b =? -1))))).
    { simpl64. forward. forward. entailer!. simpl64. zcases. }
    { simpl64. forward. entailer!. simpl64. zcases. }
    forward_if.
    { apply andb_prop in H as [E1 E2]. apply Z.eqb_eq in E1, E2. subst a b.
      rewrite st_of_ovf, out_of_ovf by (rewrite div_m1; rep_lia).
      forward_call. forward. forward_call. unfold Inv. entailer!. }
    { assert (NM: ~ (a = MIN /\ b = -1))
        by (intros [E1 E2]; rewrite E1, E2 in H; rewrite !Z.eqb_refl in H; discriminate H).
      rewrite st_of_ok, out_of_ok by (apply div_fits; auto).
      forward_call. forward. forward. forward_call (a, b). forward. forward_call.
      { assert_ok. }
      unfold Inv. entailer!. } }
  unfold Inv. Intros.
  (* vx_ceildiv *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward.
  forward_if (Inv v_a v_b v_r gv a b).
  { simpl64. subst b. rewrite div_st_zero, div_out_zero.
    forward_call. forward. forward_call. unfold Inv. entailer!. }
  { simpl64. rewrite div_st_nz, div_out_nz by auto.
    forward.
    join_temp _t'15 (Vint (Int.repr (Z.b2z ((a =? MIN) && (b =? -1))))).
    { simpl64. forward. forward. entailer!. simpl64. zcases. }
    { simpl64. forward. entailer!. simpl64. zcases. }
    forward_if.
    { apply andb_prop in H as [E1 E2]. apply Z.eqb_eq in E1, E2. subst a b.
      rewrite st_of_ovf, out_of_ovf by (rewrite ceildiv_m1; rep_lia).
      forward_call. forward. forward_call. unfold Inv. entailer!. }
    { assert (NM: ~ (a = MIN /\ b = -1))
        by (intros [E1 E2]; rewrite E1, E2 in H; rewrite !Z.eqb_refl in H; discriminate H).
      rewrite st_of_ok, out_of_ok by (apply ceildiv_fits; auto).
      forward_call. forward. forward. forward_call (a, b). forward. forward_call.
      { assert_ok. }
      unfold Inv. entailer!. } }
  unfold Inv. Intros.
  (* vx_quotient *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward.
  forward_if (Inv v_a v_b v_r gv a b).
  { simpl64. subst b. rewrite div_st_zero, div_out_zero.
    forward_call. forward. forward_call. unfold Inv. entailer!. }
  { simpl64. rewrite div_st_nz, div_out_nz by auto.
    forward.
    join_temp _t'18 (Vint (Int.repr (Z.b2z ((a =? MIN) && (b =? -1))))).
    { simpl64. forward. forward. entailer!. simpl64. zcases. }
    { simpl64. forward. entailer!. simpl64. zcases. }
    forward_if.
    { apply andb_prop in H as [E1 E2]. apply Z.eqb_eq in E1, E2. subst a b.
      rewrite st_of_ovf, out_of_ovf by (rewrite ediv_m1; rep_lia).
      forward_call. forward. forward_call. unfold Inv. entailer!. }
    { assert (NM: ~ (a = MIN /\ b = -1))
        by (intros [E1 E2]; rewrite E1, E2 in H; rewrite !Z.eqb_refl in H; discriminate H).
      rewrite st_of_ok, out_of_ok by (apply ediv_fits; auto).
      forward_call. forward. forward. forward_call (a, b). forward. forward_call.
      { assert_ok. }
      unfold Inv. entailer!. } }
  unfold Inv. Intros.
  (* vx_modulo *)
  forward. forward. forward. forward_call (a, b, v_r, Tsh, Vlong (Int64.repr 12345)). forward.
  forward.
  forward_if (Inv v_a v_b v_r gv a b).
  { simpl64. subst b. forward_call. forward. forward_call. unfold Inv. entailer!. }
  { simpl64. rewrite (proj2 (Z.eqb_neq b 0)) by auto.
    forward.
    join_temp _t'21 (Vint (Int.repr (Z.b2z ((a =? MIN) && (b =? -1))))).
    { simpl64. forward. forward. entailer!. simpl64. zcases. }
    { simpl64. forward. entailer!. simpl64. zcases. }
    forward_if.
    { apply andb_prop in H as [E1 E2]. apply Z.eqb_eq in E1, E2. subst a b.
      rewrite emod_m1.
      forward_call. forward. forward_call. unfold Inv. entailer!. }
    { assert (NM: ~ (a = MIN /\ b = -1))
        by (intros [E1 E2]; rewrite E1, E2 in H; rewrite !Z.eqb_refl in H; discriminate H).
      forward_call. forward. forward. forward_call (a, b). forward. forward_call.
      { assert_ok. }
      unfold Inv. entailer!. } }
  unfold Inv. Intros.
  forward.
  Exists (Int.repr 0). entailer!.
Qed.



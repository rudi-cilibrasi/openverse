   CONTRACT: harness/store_rollback_model.c, generated by quickproof/tools/new_contract.py.

   The theorem is QuickProof.Contract.harness_safe of the whole program: the
   harness harness/store_rollback_model.c linked with the units it needs (per-law linking,
